"""FastAPI service skeleton: the endpoint n8n calls to trigger an agent run.

Boundary (what this skeleton deliberately does NOT do): no real LLM calls,
no live n8n calls, no agent logic — that is B2's leg. The default executor
returns a skeleton result that says so honestly, and the endpoint reports
it with status="stub", never "complete".

TRUST BOUNDARY (F-B1-1, F-B1-6): the ONLY secret holder is n8n, presenting
AGENT_SHARED_SECRET, and the service is reachable ONLY on the private
network between n8n and this service — never exposed publicly. There is
no per-caller ownership on run records: anyone holding the shared secret
can replay a run_id. That is why run_ids MUST be unguessable UUIDv4
values generated by n8n (enforced below): a predictable run_id is
enumerable by any secret holder. Rate limiting and body-size limits are
NOT enforced in this code; they are deployment controls (reverse proxy
in front of the service on the private network — an example config
ships at deploy/nginx.conf.example, see README; it is an example to
adapt, not a deployed control).

/health is intentionally unauthenticated: it is a liveness probe only
and returns no data about runs, config, or credentials.
"""

import logging
import os
import uuid
from typing import Any, Callable

from fastapi import FastAPI, Header, HTTPException
from pydantic import BaseModel, field_validator

from app.runs import InMemoryRunStore
from app.security import verify_shared_secret

logger = logging.getLogger("b1_service")

#: Marker the stub executor sets so the endpoint can tell "no agent logic
#: ran" apart from a real completed run. A real executor must NOT set it.
STUB_AGENT_LOGIC = "not_implemented"


class AgentRunRequest(BaseModel):
    """Request n8n sends. run_id is client-supplied and is the idempotency key."""

    run_id: str
    input: dict[str, Any] = {}

    @field_validator("run_id")
    @classmethod
    def run_id_must_be_unguessable_uuid(cls, value: str) -> str:
        """Reject empty/whitespace/predictable run_ids (B1-6, F-B1-1).

        run_id must be a canonical UUIDv4 string. n8n generates it; the
        service never invents one, so a caller that cannot generate a
        UUID gets a 422, not a guessable fallback.
        """
        if not value.strip():
            raise ValueError("run_id must not be empty or whitespace-only")
        try:
            parsed = uuid.UUID(value)
        except ValueError:
            raise ValueError("run_id must be a UUID (unguessable; generate a UUIDv4)") from None
        if str(parsed) != value or parsed.version != 4:
            raise ValueError("run_id must be a canonical UUIDv4 string")
        return value


class AgentRunResponse(BaseModel):
    run_id: str
    input: dict[str, Any]
    status: str  # "complete" | "stub" | "failed"
    result: dict[str, Any]


def _skeleton_executor(run_id: str, run_input: dict[str, Any]) -> dict[str, Any]:
    return {
        "agent_logic": STUB_AGENT_LOGIC,
        "detail": "Skeleton only; agent logic is a later leg (B2). No LLM or live n8n call was made.",
    }


def create_app(
    run_store: InMemoryRunStore | None = None,
    executor: Callable[[str, dict[str, Any]], dict[str, Any]] | None = None,
) -> FastAPI:
    """Build the app. Dependencies are injectable so tests need no live services."""
    store = run_store or InMemoryRunStore()
    run_executor = executor or _skeleton_executor
    app = FastAPI(title="3rd Eye Supply agent service (skeleton)")

    @app.get("/health")
    def health() -> dict[str, str]:
        # Intentionally unauthenticated liveness probe; returns no data.
        return {"status": "ok"}

    @app.post("/agent/run", response_model=AgentRunResponse)
    def agent_run(
        request: AgentRunRequest,
        x_agent_shared_secret: str | None = Header(default=None, alias="X-Agent-Shared-Secret"),
    ) -> AgentRunResponse:
        expected = os.environ.get("AGENT_SHARED_SECRET")
        if not verify_shared_secret(x_agent_shared_secret, expected):
            # Log the attempt, never the secret (presented or expected).
            logger.warning("rejected /agent/run attempt: bad or missing shared secret")
            raise HTTPException(status_code=401, detail="unauthorized")
        _, record = store.create_or_get(
            request.run_id, request.input, lambda: run_executor(request.run_id, request.input)
        )
        # F-B1-1: a duplicate run_id with DIFFERENT input is a conflict.
        # Return 409 with NO stored result and NO stored input in the body:
        # the caller has not proven it owns the original run.
        if record["input"] != request.input:
            raise HTTPException(
                status_code=409, detail="run_id already used with different input"
            )
        if record["status"] == "failed":
            return AgentRunResponse(
                run_id=request.run_id,
                input=record["input"],
                status="failed",
                result={"error": record["error"] or "executor failed"},
            )
        result = record["result"] or {}
        # B1-3: the stub is never reported as a completed real run.
        status = "stub" if result.get("agent_logic") == STUB_AGENT_LOGIC else "complete"
        return AgentRunResponse(
            run_id=request.run_id,
            input=record["input"],
            status=status,
            result=result,
        )

    return app


app = create_app()
